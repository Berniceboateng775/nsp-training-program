// ─── Render Sidebar ──────────────────────────────────────

function renderSidebar(activePage) {
    const user = api.getUser();
    const initial = user ? user.name.charAt(0).toUpperCase() : '?';
    
    const sidebarHTML = `
        <div class="sidebar-overlay" onclick="closeSidebar()"></div>
        <button class="mobile-toggle" onclick="toggleSidebar()" aria-label="Toggle menu">
            ${icons.menu}
        </button>
        <aside class="sidebar" id="sidebar">
            <div class="sidebar-logo">
                <div class="logo-icon">${icons.bookOpen}</div>
                <h2>Vellichor</h2>
            </div>
            <nav class="sidebar-nav">
                ${navItems.map(item => `
                    <a href="${item.href}" class="nav-item ${activePage === item.href ? 'active' : ''}">
                        ${icons[item.icon]}
                        <span>${item.label}</span>
                    </a>
                `).join('')}
            </nav>
            <div class="sidebar-footer">
                <div class="sidebar-user">
                    <div class="user-avatar">${initial}</div>
                    <div class="user-info">
                        <div class="user-name">${user ? user.name : 'Guest'}</div>
                        <div class="user-email">${user ? user.email : ''}</div>
                    </div>
                </div>
                <button class="nav-item" style="margin-top: var(--space-2); width: 100%; color: var(--color-text-muted);" onclick="api.logout()">
                    ${icons.logOut}
                    <span>Sign Out</span>
                </button>
            </div>
        </aside>
    `;
    
    document.body.insertAdjacentHTML('afterbegin', sidebarHTML);
}

function toggleSidebar() {
    const sidebar = document.getElementById('sidebar');
    const overlay = document.querySelector('.sidebar-overlay');
    sidebar.classList.toggle('open');
    overlay.classList.toggle('open');
}

function closeSidebar() {
    const sidebar = document.getElementById('sidebar');
    const overlay = document.querySelector('.sidebar-overlay');
    sidebar.classList.remove('open');
    overlay.classList.remove('open');
}


// ─── Route Guard ─────────────────────────────────────────

function requireAuth() {
    if (!api.isLoggedIn()) {
        window.location.href = 'login.html';
        return false;
    }
    return true;
}


// ─── Toast Notifications ─────────────────────────────────

function showToast(message, type = 'success') {
    let container = document.querySelector('.toast-container');
    if (!container) {
        container = document.createElement('div');
        container.className = 'toast-container';
        document.body.appendChild(container);
    }

    const toast = document.createElement('div');
    toast.className = `toast ${type}`;
    toast.textContent = message;
    container.appendChild(toast);

    setTimeout(() => {
        toast.style.opacity = '0';
        toast.style.transform = 'translateY(-10px)';
        setTimeout(() => toast.remove(), 300);
    }, 3500);
}


// ─── Format Date ─────────────────────────────────────────

function formatDate(dateStr) {
    if (!dateStr) return '';
    const date = new Date(dateStr);
    return date.toLocaleDateString('en-US', {
        month: 'short',
        day: 'numeric',
        year: 'numeric'
    });
}

function timeAgo(dateStr) {
    if (!dateStr) return '';
    const now = new Date();
    const date = new Date(dateStr);
    const diff = Math.floor((now - date) / 1000);
    
    if (diff < 60) return 'just now';
    if (diff < 3600) return `${Math.floor(diff/60)}m ago`;
    if (diff < 86400) return `${Math.floor(diff/3600)}h ago`;
    return `${Math.floor(diff/86400)}d ago`;
}
